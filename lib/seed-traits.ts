// Допоміжна функція: вибрати N випадкових елементів
export function pickRandom<T>(arr: T[], n: number): T[] {
  const shuffled = [...arr].sort(() => Math.random() - 0.5)
  return shuffled.slice(0, Math.min(n, arr.length))
}

// Згенерувати набір рис для NPC
export function generateTraits(tribe: string): string {
  const general = pickRandom(GENERAL_TRAITS, 3)
  const species = SPECIES_TRAITS[tribe] ? pickRandom(SPECIES_TRAITS[tribe], 2) : []
  return [...general, ...species].join(', ')
}

// Випадковий архетип
export function randomArchetype(): string {
  return NPC_ARCHETYPES[Math.floor(Math.random() * NPC_ARCHETYPES.length)]
}
